function optionList(it, mode, ruOn){
  var tr = ruOn ? tq(it.q) : null;
  /* mode: 'play' | 'feedback' | 'review' */
  var q = it.q, multi = needCount(q) > 1;
  return h('div', {class:'opts', role: multi ? 'group' : 'radiogroup'},
    it.order.map(function(oi, pos){
      var o = q.opts[oi], sel = it.sel.has(oi), cls = 'opt ' + (multi ? 'multi' : 'single'), vd = '';
      if (mode !== 'play'){
        if (o.ok && sel){ cls += ' ok'; vd = t('верно', 'correct'); }
        else if (!o.ok && sel){ cls += ' bad'; vd = t('неверно', 'wrong'); }
        else if (o.ok && !sel){ cls += ' missed'; vd = t('нужно было выбрать', 'should have been selected'); }
      }
      var attrs = {class:cls, type:'button', role: multi ? 'checkbox' : 'radio', 'aria-checked': String(sel), disabled: mode !== 'play'};
      if (mode === 'play') attrs.onclick = function(){ toggleOpt(oi); };
      var mark = mode === 'play' ? (sel ? '✓' : (pos < 9 ? String(pos + 1) : '')) : (sel || o.ok ? (o.ok ? '✓' : '✕') : '');
      return h('button', attrs,
        h('span', {class:'mk', 'aria-hidden':'true'}, mark),
        h('span', {class:'tx'}, h('span', {lang:'en'}, o.t), tr ? h('span', {class:'ru', lang:ui()}, tr.o[oi]) : null),
        vd ? h('span', {class:'vd'}, vd) : null);
    }));
}

